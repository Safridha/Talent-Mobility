CREATE TABLE web_push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_id BIGINT REFERENCES applicants(id) ON DELETE CASCADE,
    admin_id BIGINT REFERENCES admins(id) ON DELETE CASCADE,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (num_nonnulls(applicant_id, admin_id) = 1)
);

CREATE INDEX web_push_subscriptions_applicant_idx
    ON web_push_subscriptions (applicant_id)
    WHERE applicant_id IS NOT NULL;

CREATE INDEX web_push_subscriptions_admin_idx
    ON web_push_subscriptions (admin_id)
    WHERE admin_id IS NOT NULL;
